#!/usr/bin/env python3
"""Explicitly regenerate embedded guest benchmark fixtures and reference CRCs."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import zlib
from PIL import Image, features


def generate(output):
    output.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by tools/generate_webp_bench.py; do not edit. */']
    entries, manifest = [], []
    for size in (512, 4096):
        ramp = Image.linear_gradient('L').resize((size, size))
        across = ramp.transpose(Image.Transpose.TRANSPOSE)
        rgb = Image.merge('RGB', (across, ramp, across))
        for mode in ('lossy', 'lossless', 'alpha'):
            name = f'{mode}_{size}'
            image = Image.merge('RGBA', (*rgb.split(), ramp)) if mode == 'alpha' else rgb
            stream = io.BytesIO()
            image.save(stream, 'WEBP', lossless=mode == 'lossless', quality=80,
                       method=3, exact=True)
            data = stream.getvalue()
            reference = Image.open(io.BytesIO(data)).convert('RGBA').tobytes('raw', 'BGRA')
            crc = zlib.crc32(reference)
            lines.append(f'static const uint8_t {name}[] = {{')
            lines.extend('    ' + ','.join(f'0x{b:02x}' for b in data[i:i+16]) + ','
                         for i in range(0, len(data), 16))
            lines.append('};')
            entries.append(f'    {{"{name}", {name}, sizeof({name}), {size}, '
                           f'0x{zlib.crc32(data):08x}u, 0x{crc:08x}u}},')
            manifest.append(dict(name=name, size=size, input_bytes=len(data),
                                 input_sha256=hashlib.sha256(data).hexdigest(),
                                 pixel_crc32=f'{crc:08x}'))
    lines += ['static const fixture_t fixtures[] = {', *entries, '};']
    (output/'fixtures.h').write_text('\n'.join(lines)+'\n')
    (output/'fixtures.json').write_text(json.dumps(dict(
        encoder='Pillow libwebp '+features.version('webp'), fixtures=manifest), indent=2)+'\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    generate(parser.parse_args().output)
