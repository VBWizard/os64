#!/usr/bin/env python3
"""Write userland/tests/avtest/sine_m4a.h, the MP4 /tests/avtest decodes.

    tools/gen_avtest_m4a.py

An MP4 holding a video track first (a 16x16 picture, FFmpeg's own MPEG-4
encoder, which no decoder here reads) and then one second of a 440 Hz sine
at 44.1 kHz, mono, amplitude 1/8, in AAC-LC at 64 kb/s (FFmpeg's own AAC
encoder): the shape of a video file whose sound is what os64 plays of it
(AUDIO_YONDER.md § Y.4, § Y.5), and of the placeholder a podcast site's
player loads first.

The bytes are committed, so the build never needs the host's ffmpeg; this
script is how they were made. Beside them it writes the sample count and
energy the host's ffmpeg decodes them to with its assembly switched off
(-cpuflags 0, the C path the port builds): AAC is lossy, so the reference
is a measurement of THESE bytes, and re-running the script with another
encoder re-measures it. The reference is the sound's ENERGY (the sum of
its squared samples), not its level averaged over the count: releases of
FFmpeg trim the encoder's priming differently, and the near-silence they
keep or drop changes the count and the average, never the energy.
"""
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'userland/tests/avtest/sine_m4a.h'

with tempfile.TemporaryDirectory() as tmp:
    mp4 = Path(tmp) / 'sine.mp4'
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error',
                    '-f', 'lavfi', '-i', 'color=c=black:s=16x16:r=10:d=1',
                    '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=44100:duration=1',
                    '-map', '0:v', '-map', '1:a', '-c:v', 'mpeg4', '-ac', '1', '-c:a', 'aac', '-b:a', '64k',
                    '-bitexact', '-fflags', '+bitexact', '-movflags', '+faststart', str(mp4)], check=True)
    data = mp4.read_bytes()
    pcm = subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-cpuflags', '0',
                          '-i', str(mp4), '-map', '0:a', '-f', 'f32le', '-'],
                         check=True, capture_output=True).stdout
    samples = struct.unpack(f'<{len(pcm) // 4}f', pcm)
    energy_ppm = round(sum(x * x for x in samples) * 1e6)

lines = ['// GENERATED by tools/gen_avtest_m4a.py: an MP4 with a 16x16 MPEG-4 video track,',
         '// then a 440 Hz sine, one second, 44.1 kHz mono, AAC-LC 64 kb/s.',
         '// Not edited by hand.',
         '#include <stdint.h>',
         f'static const uint8_t kSineM4a[{len(data)}] = {{']
for i in range(0, len(data), 16):
    lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
lines.append('};')
lines.append(f'// What the host\'s ffmpeg (C path) decodes the sound to: {len(samples)} samples,')
lines.append('// holding this energy (the sum of the squared samples, full scale 1), in millionths.')
lines.append(f'#define SINE_M4A_SAMPLES {len(samples)}')
lines.append(f'#define SINE_M4A_ENERGY_PPM {energy_ppm}')
OUT.write_text('\n'.join(lines) + '\n')
print(f'wrote {OUT.relative_to(ROOT)}: {len(data)} bytes of MP4, {len(samples)} samples, energy {energy_ppm} ppm')
