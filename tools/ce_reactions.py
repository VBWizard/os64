#!/usr/bin/env python3
"""The [CEReactions] table (docs/design/pending/CUSTOM_ELEMENTS.md, cut b2).

Reads dom.idl, html.idl and cssom.idl from the pinned WPT checkout and writes
userland/libdom/ce_reactions.inc: one row for every [CEReactions] operation
and every attribute whose setter is [CEReactions], by interface. libdom's
custom elements row wraps each member it has, so its reactions run before it
returns (custom.c, d_reactions_wrap).

    tools/ce_reactions.py            write the table from $WPT_DIR (or .vendor/wpt)
    tools/ce_reactions.py --check    fail when the table is not what the IDL says
    tools/ce_reactions.py --selftest the parser against a sample of every shape

A mixin's members are rows of each interface that includes it, and a partial
interface's are its interface's. Three kinds of row:
  METHOD   an operation: its function is replaced;
  SETTER   an attribute: its setter is replaced, its getter kept;
  EXOTIC   a special operation (an unnamed setter or deleter), which no
           prototype member is: what it changes reaches the backup element
           queue and runs at the checkpoint. Listed so the DOM host can name
           each one.
And one row the IDL cannot write: CSSStyleDeclaration's property attributes
(camel-cased, dashed, webkit-cased) are [CEReactions] in CSSOM, which names
them as a class and not one by one, so the table says ALL_SETTERS for that
prototype.
"""
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABLE = ROOT / 'userland/libdom/ce_reactions.inc'
FILES = ('dom.idl', 'html.idl', 'cssom.idl')

DEFINITION = re.compile(r'(partial\s+)?interface\s+(mixin\s+)?(\w+)\s*(?::\s*\w+\s*)?\{')
INCLUDES = re.compile(r'(\w+)\s+includes\s+(\w+)\s*;')


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', text)


def body_at(text, open_brace):
    """The text between the brace at open_brace and its match."""
    depth = 0
    for i in range(open_brace, len(text)):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return text[open_brace + 1:i]
    raise ValueError('unbalanced braces')


def attributes(member):
    """The leading extended attributes of a member and the rest of it."""
    member = member.strip()
    if not member.startswith('['):
        return '', member
    depth = 0
    for i, ch in enumerate(member):
        depth += ch == '['
        depth -= ch == ']'
        if depth == 0:
            return member[1:i], member[i + 1:].strip()
    raise ValueError('unbalanced extended attributes: ' + member)


def rows_of(member):
    """(name, kind) for one member, or None when it is not [CEReactions]."""
    ext, rest = attributes(member)
    if not re.search(r'\bCEReactions\b', ext):
        return None
    rest = re.sub(r'\[[^\]]*\]', ' ', rest)  # attributes on types and arguments
    if re.search(r'\battribute\b', rest):
        name = re.findall(r'(\w+)\s*$', rest.strip())
        return (name[0], 'SETTER') if name else None
    head = rest.split('(', 1)[0].split()
    if head and head[0] in ('getter', 'setter', 'deleter'):
        named = head[-1] if len(head) > 2 else None
        if named is None:
            return ('(' + head[0] + ')', 'EXOTIC')
        return (named, 'METHOD')
    return (head[-1], 'METHOD') if head else None


def parse(texts):
    """Every [CEReactions] row of the IDL texts: (interface, member, kind)."""
    members, includes = {}, []
    for text in texts:
        text = strip_comments(text)
        includes += INCLUDES.findall(text)
        for match in DEFINITION.finditer(text):
            name = match.group(3)
            body = body_at(text, match.end() - 1)
            for member in body.split(';'):
                row = rows_of(member)
                if row:
                    members.setdefault(name, set()).add(row)
    rows = set()
    mixins = {}
    for target, mixin in includes:
        mixins.setdefault(mixin, []).append(target)
    for name, found in members.items():
        for target in mixins.get(name, [name]):
            rows |= {(target, member, kind) for member, kind in found}
    if any(i == 'CSSStyleDeclaration' for i, _, _ in rows):
        rows.add(('CSSStyleDeclaration', '*', 'ALL_SETTERS'))
    return sorted(rows)


def table(rows, pin):
    lines = ['/* GENERATED by tools/ce_reactions.py from WPT %s\'s dom.idl, html.idl and' % pin,
             ' * cssom.idl: every [CEReactions] member, by interface. Do not edit; run the',
             ' * tool, and its --check holds this file to the IDL. */']
    for interface, member, kind in rows:
        lines.append('{"%s", "%s", D_CE_%s},' % (interface, member, kind))
    return '\n'.join(lines) + '\n'


def pin():
    text = (ROOT / 'tools/wpt_fetch.sh').read_text()
    return re.search(r'WPT_COMMIT=(\w+)', text).group(1)


def read_idl():
    wpt = pathlib.Path(os.environ.get('WPT_DIR', ROOT / '.vendor/wpt'))
    paths = [wpt / 'interfaces' / f for f in FILES]
    missing = [str(p) for p in paths if not p.is_file()]
    if missing:
        sys.exit('ce_reactions: no ' + ', '.join(missing) + '; run tools/wpt_fetch.sh (WPT_DIR elsewhere)')
    return [p.read_text() for p in paths]


SAMPLE = r'''
interface Node : EventTarget {
  [CEReactions] attribute DOMString? textContent; // a comment
  readonly attribute Node? parentNode;
  [CEReactions] Node appendChild(Node node);
  Node? lookup();
};
/* a [CEReactions] comment */
partial interface Node { [CEReactions] undefined normalize(); };
interface mixin ParentNode {
  [CEReactions, Unscopable] undefined append((Node or DOMString)... nodes);
};
Document includes ParentNode;
Element includes ParentNode;
interface DOMTokenList { [CEReactions] stringifier attribute DOMString value; };
interface DOMStringMap {
  [CEReactions] setter undefined (DOMString name, DOMString value);
  [CEReactions] deleter undefined (DOMString name);
};
interface Element {
  [CEReactions, Reflect] attribute DOMString id;
  [CEReactions] attribute (TrustedHTML or [LegacyNullToEmptyString] DOMString) innerHTML;
};
dictionary Options { boolean flag = false; };
interface CSSStyleDeclaration { [CEReactions] attribute CSSOMString cssText; };
'''
SAMPLE_ROWS = [
    ('CSSStyleDeclaration', '*', 'ALL_SETTERS'), ('CSSStyleDeclaration', 'cssText', 'SETTER'),
    ('DOMStringMap', '(deleter)', 'EXOTIC'), ('DOMStringMap', '(setter)', 'EXOTIC'),
    ('DOMTokenList', 'value', 'SETTER'), ('Document', 'append', 'METHOD'),
    ('Element', 'append', 'METHOD'), ('Element', 'id', 'SETTER'), ('Element', 'innerHTML', 'SETTER'),
    ('Node', 'appendChild', 'METHOD'), ('Node', 'normalize', 'METHOD'), ('Node', 'textContent', 'SETTER'),
]


def main():
    if sys.argv[1:] == ['--selftest']:
        got = parse([SAMPLE])
        if got != SAMPLE_ROWS:
            sys.exit('ce_reactions selftest: got\n  %s\nwant\n  %s' % (got, SAMPLE_ROWS))
        print('ce_reactions selftest: every shape read as the sample says')
        return
    text = table(parse(read_idl()), pin())
    if sys.argv[1:] == ['--check']:
        if not TABLE.is_file() or TABLE.read_text() != text:
            sys.exit('ce_reactions: %s is not what the IDL says; run tools/ce_reactions.py' % TABLE)
        print('ce_reactions: the table is the IDL\'s')
        return
    if sys.argv[1:]:
        sys.exit('usage: tools/ce_reactions.py [--check | --selftest]')
    TABLE.write_text(text)
    print('ce_reactions: %d rows' % text.count('\n{'))


if __name__ == '__main__':
    main()
