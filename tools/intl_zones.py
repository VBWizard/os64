#!/usr/bin/env python3
"""Generate libjs's time-zone table (userland/libjs/intl/zones.inc).

Usage: tools/intl_zones.py <cldr-bcp47 dir> <cldr-core dir> [zoneinfo dir] > userland/libjs/intl/zones.inc

INTL.md § 5. The NAMES are CLDR's (bcp47/timezone.json, the set other
browsers' ICU accepts): each entry's aliases, the first its canonical name,
which is what resolvedOptions().timeZone answers (`Asia/Kolkata` is
`Asia/Calcutta`, `US/Eastern` and `EST5EDT` are `America/New_York`), with
ECMA-402's rule that the UTC and GMT groups are `UTC`. A name CLDR marks
unknown (`Etc/Unknown`, `Factory`) is absent, so it is a RangeError. The
RULES are tzdata's: each zone's TZif footer, the POSIX string of its
current rule, from the zoneinfo files of the machine that runs this, whose
version the table names. Both versions are written into the table's head.

The table, sorted by name folded to lowercase for a binary search:
  kZoneRules[]   the distinct rules
  kZoneNames[]   {name, canonical (an index into kZoneNames), rule, listed}
                 `listed`: a name Intl.supportedValuesOf("timeZone") lists
  kRulePreferred[] for each rule, the canonical zone a host TZ written as
                 that rule names (INTL.md § 5: the metazone's golden zone
                 when one carries the rule, else the first by name)
"""
import json
import os
import re
import sys


def footer(path):
    try:
        data = open(path, 'rb').read()
    except OSError:
        return None
    if not data.startswith(b'TZif'):
        return None
    return data.rstrip(b'\n').rsplit(b'\n', 1)[-1].decode('ascii')


def main():
    bcp47, core = sys.argv[1], sys.argv[2]
    zoneinfo = sys.argv[3] if len(sys.argv) > 3 else '/usr/share/zoneinfo'
    tzdata_version = 'unknown'
    try:
        with open(os.path.join(zoneinfo, 'tzdata.zi')) as f:
            first = f.readline().strip()
            if first.startswith('# version '):
                tzdata_version = first[len('# version '):]
    except OSError:
        pass
    with open(os.path.join(bcp47, 'package.json')) as f:
        cldr_version = json.load(f)['version']
    zones = json.load(open(os.path.join(bcp47, 'bcp47', 'timezone.json')))['keyword']['u']['tz']
    meta = json.load(open(os.path.join(core, 'supplemental', 'metaZones.json')))['supplemental']['metaZones']
    golden = {m['mapZone']['_type'] for m in meta['metazones']
              if m['mapZone'].get('_territory') == '001'} if 'metazones' in meta else set()

    entries = []        # (name, canonical name, rule, listed)
    for key, value in sorted(zones.items()):
        if not isinstance(value, dict) or '_alias' not in value or key == 'unk':
            continue
        aliases = value['_alias'].split()
        canonical = aliases[0]
        group_utc = key in ('utc', 'gmt')
        if group_utc:
            canonical = 'UTC'
        rule = None
        for name in ([value.get('_iana')] if value.get('_iana') else []) + aliases:
            rule = footer(os.path.join(zoneinfo, name))
            if rule is not None:
                break
        if rule is None:
            sys.exit('intl_zones: no zoneinfo rule for ' + canonical)
        if group_utc:
            rule = 'UTC0'
        # Listed: a zone's canonical name, not the UTC group's nor the
        # Etc/GMT±N offsets, which other browsers' lists leave out.
        listed = not group_utc and not canonical.startswith('Etc/') and not value.get('_deprecated')
        for i, name in enumerate(aliases + (['UTC'] if group_utc and 'UTC' not in aliases else [])):
            entries.append((name, canonical, rule, listed and name == canonical))
        if group_utc and not any(e[0] == 'UTC' for e in entries):
            entries.append(('UTC', 'UTC', rule, False))
    by_name = {}
    for e in entries:
        by_name.setdefault(e[0].lower(), e)
    names = sorted(by_name.values(), key=lambda e: e[0].lower())
    index = {e[0]: i for i, e in enumerate(names)}
    rules = sorted({e[2] for e in names})
    rule_index = {r: i for i, r in enumerate(rules)}
    for e in names:
        if e[1] not in index:
            sys.exit('intl_zones: canonical %s is not itself a name' % e[1])

    preferred = []
    for r in rules:
        carriers = sorted({e[1] for e in names if e[2] == r and e[1] == e[0] and e[3]})
        pick = next((z for z in carriers if z in golden), carriers[0] if carriers else None)
        if pick is None:
            pick = next(e[1] for e in names if e[2] == r)
        preferred.append(index[pick])

    out = sys.stdout
    out.write('/* GENERATED by tools/intl_zones.py: do not edit. CLDR %s (names), '
              'tzdata %s (rules). INTL.md § 5. */\n' % (cldr_version, tzdata_version))
    out.write('#define INTL_ZONES_CLDR "%s"\n#define INTL_ZONES_TZDATA "%s"\n' % (cldr_version, tzdata_version))
    out.write('static const char *const kZoneRules[] = {\n')
    for r in rules:
        out.write('    "%s",\n' % r)
    out.write('};\n')
    out.write('static const IntlZoneName kZoneNames[] = {\n')
    for name, canonical, rule, listed in names:
        out.write('    {"%s", %d, %d, %d},\n' % (name, index[canonical], rule_index[rule], 1 if listed else 0))
    out.write('};\n')
    out.write('static const uint16_t kRulePreferred[] = {\n   ')
    for i, p in enumerate(preferred):
        out.write(' %d,' % p)
        if i % 16 == 15:
            out.write('\n   ')
    out.write('\n};\n')
    listed = sorted(e[0] for e in names if e[3])
    sys.stderr.write('intl_zones: %d names, %d canonical listed, %d rules (CLDR %s, tzdata %s)\n'
                     % (len(names), len(listed), len(rules), cldr_version, tzdata_version))


if __name__ == '__main__':
    main()
