#!/usr/bin/env python3
"""Make the deterministic image-memory comparison pages and their PNG."""

from pathlib import Path
import struct
import zlib

PAGES = Path(__file__).resolve().parent / "pages"


def chunk(kind, body):
    return (struct.pack(">I", len(body)) + kind + body
            + struct.pack(">I", zlib.crc32(kind + body)))


def main():
    width, height = 1920, 1080
    # Solid blue makes immediate Canvas readback independent of filtering.
    rows = (b"\0" + bytes((32, 96, 192, 255)) * width) * height
    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))
    (PAGES / "image-memory.png").write_bytes(png)
    links = " | ".join(f'<a href="image-memory-{m}.html">{m}</a>'
                       for m in ("untouched", "metadata", "canvas"))
    for mode in ("untouched", "metadata", "canvas"):
        script = ""
        canvas = ""
        result = "The image is displayed; no script accesses it."
        if mode != "untouched":
            result = "Waiting for the image load event."
            action = "out.textContent = 'PASS: natural size ' + img.naturalWidth + ' x ' + img.naturalHeight;"
            if mode == "canvas":
                canvas = '<canvas id="copy" width="160" height="90"></canvas>'
                action = """var ctx = document.getElementById('copy').getContext('2d');
    ctx.drawImage(img, 0, 0, 160, 90);
    var pixel = ctx.getImageData(80, 45, 1, 1).data;
    out.textContent = pixel[0] === 32 && pixel[1] === 96 && pixel[2] === 192 && pixel[3] === 255
      ? 'PASS: one draw in onload, immediate blue readback.' : 'FAIL: immediate readback differs.';"""
            script = """<script>
var img = document.getElementById('source');
var out = document.getElementById('result');
var loads = 0;
img.onload = function () {
  if (++loads !== 1) { out.textContent = 'FAIL: duplicate load event.'; return; }
  if (img.naturalWidth !== 1920 || img.naturalHeight !== 1080 || !img.complete) {
    out.textContent = 'FAIL: loaded image metadata differs.'; return;
  }
  %s
};
img.onerror = function () { out.textContent = 'FAIL: image error.'; };
</script>""" % action
        page = f"""<!doctype html>
<!-- Generated by tools/generate_image_memory_fixture.py. -->
<html lang="en"><head><meta charset="utf-8"><title>Image memory: {mode}</title>
<style>body {{ margin:24px; font:16px sans-serif; }} img,canvas {{ display:block; margin:16px 0; }}</style>
</head><body><h1>Image memory: {mode}</h1><p>{links}</p>
<p>A 1920 x 1080 source displayed at 160 x 90. Compare at 100% zoom.</p>
<img id="source" src="image-memory.png" width="160" height="90" alt="Solid blue rectangle">
{canvas}<p id="result">{result}</p>
{script}</body></html>
"""
        (PAGES / f"image-memory-{mode}.html").write_text(page)


    (PAGES / "image-memory-preload.css").write_text(
        "#source { width:160px; max-width:100%; height:auto; }\n")
    modes = ("active", "inactive", "ordinary")
    links = " | ".join(f'<a href="image-memory-preload-{m}.html">{m}</a>' for m in modes)
    for mode in modes:
        relation = 'rel="stylesheet"' if mode == "ordinary" else 'rel="preload" as="style"'
        activation = ' onload="this.onload=null;this.rel=\'stylesheet\'"' if mode == "active" else ""
        expected = 1920 if mode == "inactive" else 160
        page = f"""<!doctype html>
<!-- Generated by tools/generate_image_memory_fixture.py. -->
<html lang="en"><head><meta charset="utf-8"><title>Stylesheet preload: {mode}</title>
<style>body {{ margin:24px; font:16px sans-serif; }} img {{ display:block; }}</style>
<link id="sheet" {relation} href="image-memory-preload.css"{activation}>
</head><body><h1>Stylesheet preload: {mode}</h1><p>{links}</p>
<p>At 100% zoom the expected image width is {expected} CSS pixels.
The inactive page deliberately keeps the large image and horizontal overflow.</p>
<p id="result">Waiting for stylesheet events.</p>
<img id="source" src="image-memory.png" width="1920" height="1080" alt="Solid blue rectangle">
<script>
function checkWidth() {{
  var width = document.getElementById('source').offsetWidth;
  document.getElementById('result').textContent = width === {expected}
    ? 'PASS: displayed width ' + width + ' CSS pixels.' : 'Waiting: displayed width ' + width + ' CSS pixels.';
}}
window.addEventListener('load', checkWidth);
document.getElementById('sheet').addEventListener('load', checkWidth);
document.getElementById('sheet').addEventListener('error', function () {{
  document.getElementById('result').textContent = 'FAIL: stylesheet error.';
}});
checkWidth();
</script></body></html>
"""
        (PAGES / f"image-memory-preload-{mode}.html").write_text(page)


if __name__ == "__main__":
    main()
