#!/usr/bin/env python3
"""Write userland/tests/avtest/sine_mp3.h, the MP3 /tests/avtest decodes.

    tools/gen_avtest_mp3.py

One second of a 440 Hz sine at 44.1 kHz, mono, amplitude 1/8, encoded by
the host's ffmpeg with LAME at 64 kb/s, with a Xing/LAME header (so the
decoder trims the encoder's delay and padding) and an ID3v2.3 tag whose
genre is "(17)", the ID3v1 genre-number form FFmpeg's id3v2 reader turns
into "Rock" with sscanf, which is the port's routed scanf at work.

The bytes are committed, so the build never needs the host's ffmpeg; this
script is how they were made. Beside them it writes the level the host's
ffmpeg decodes them to with its assembly switched off (-cpuflags 0, the C
path the port builds): MP3 is lossy and LAME's encode does not land at the
sine's own level, so the reference is a measurement of THESE bytes, and
re-running the script with another LAME re-measures it.
"""
import math
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'userland/tests/avtest/sine_mp3.h'

with tempfile.TemporaryDirectory() as tmp:
    mp3 = Path(tmp) / 'sine.mp3'
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-f', 'lavfi',
                    '-i', 'sine=frequency=440:sample_rate=44100:duration=1',
                    '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '64k', '-write_xing', '1',
                    '-id3v2_version', '3', '-metadata', 'title=avtest', '-metadata', 'genre=(17)',
                    '-bitexact', str(mp3)], check=True)
    data = mp3.read_bytes()
    pcm = subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-cpuflags', '0',
                          '-i', str(mp3), '-f', 'f32le', '-'], check=True, capture_output=True).stdout
    samples = struct.unpack(f'<{len(pcm) // 4}f', pcm)
    rms_ppm = round(math.sqrt(sum(x * x for x in samples) / len(samples)) * 1e6)

lines = ['// GENERATED by tools/gen_avtest_mp3.py: a 440 Hz sine, one second, 44.1 kHz',
         '// mono, LAME 64 kb/s with a Xing header and an ID3v2.3 tag (genre "(17)").',
         '// Not edited by hand.',
         '#include <stdint.h>',
         f'static const uint8_t kSineMp3[{len(data)}] = {{']
for i in range(0, len(data), 16):
    lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
lines.append('};')
lines.append(f'// What the host\'s ffmpeg (C path) decodes the bytes to: {len(samples)} samples,')
lines.append('// at this level, in millionths of full scale.')
lines.append(f'#define SINE_MP3_SAMPLES {len(samples)}')
lines.append(f'#define SINE_MP3_RMS_PPM {rms_ppm}')
OUT.write_text('\n'.join(lines) + '\n')
print(f'wrote {OUT.relative_to(ROOT)}: {len(data)} bytes of MP3, {len(samples)} samples at {rms_ppm} ppm')
